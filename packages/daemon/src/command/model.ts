import { PlanStepSchema } from "@agentboard/shared";
import type { BoardSnapshot, PlannerSettings, PlanStep } from "@agentboard/shared";

const LOOPBACK = new Set(["localhost", "127.0.0.1", "[::1]"]);
const TIMEOUT_MS = 8000;

const KINDS = `Step kinds and their fields:
- spawn: agent ("claude" | "codex" | "gemini" | "opencode"), optional worktree (branch name), optional prompt, optional near (a console id to place it beside)
- close: consoleIds (one or more console ids)
- resume: consoleId
- focus: consoleId
- fit: no fields (fit all consoles in view)
- note: text
- input: consoleId, text (typed into that console)`;

/** D45: the model sees titles, ids, agents, statuses, branches and workspaces, never terminal text. */
function systemPrompt(snapshot: BoardSnapshot): string {
  const board = {
    workspaces: snapshot.workspaces,
    activeWorkspaceId: snapshot.activeWorkspaceId,
    consoles: snapshot.consoles.map(({ id, title, agent, status, branch, workspaceId, idleSeconds }) => ({ id, title, agent, status, branch, workspaceId, idleSeconds })),
    availableAgents: snapshot.agents.filter((a) => a.available).map((a) => a.id),
  };
  return [
    "You turn one command for a board of coding-agent consoles into a plan.",
    'Answer with JSON only: {"steps":[{"kind":"...", ...fields}]}. Use only console ids from the board. An empty steps array means you could not plan it.',
    KINDS,
    "Console statuses: stopped, starting, working, idle, needs_you, exited.",
    `The board: ${JSON.stringify(board)}`,
  ].join("\n\n");
}

async function ask(text: string, snapshot: BoardSnapshot, planner: PlannerSettings, fetch: typeof globalThis.fetch, signal: AbortSignal) {
  const res = await fetch(`${planner.url.replace(/\/+$/, "")}/api/chat`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({
      model: planner.model,
      stream: false,
      format: "json",
      messages: [
        { role: "system", content: systemPrompt(snapshot) },
        { role: "user", content: text },
      ],
    }),
    signal,
  });
  if (!res.ok) throw new Error(`planner answered ${res.status}`);
  return (await res.json()) as { message?: { content?: string } };
}

/** Plans with a local Ollama-compatible model; throws on anything off so planCommand falls back to the rules. */
export async function planWithModel(text: string, snapshot: BoardSnapshot, planner: PlannerSettings, fetch: typeof globalThis.fetch): Promise<PlanStep[]> {
  const url = new URL(planner.url);
  if (!LOOPBACK.has(url.hostname)) throw new Error(`planner URL must be loopback, got ${url.hostname}`);
  // A plain timer rather than AbortSignal.timeout, so the 8 s budget follows the event loop's clock (and fake timers in tests).
  const abort = new AbortController();
  const timer = setTimeout(() => abort.abort(), TIMEOUT_MS);
  let body: { message?: { content?: string } };
  try {
    body = await ask(text, snapshot, planner, fetch, abort.signal);
  } finally {
    clearTimeout(timer);
  }
  const { steps } = JSON.parse(body.message?.content ?? "") as { steps?: unknown };
  if (!Array.isArray(steps)) throw new Error("planner answer has no steps array");
  const ids = new Set(snapshot.consoles.map((c) => c.id));
  return steps.map((raw: Record<string, unknown>) => {
    // The model's id, summary and asks are overwritten here and regenerated by planCommand.
    const step = PlanStepSchema.parse({ ...raw, id: "", summary: "", asks: false });
    const refs = [..."consoleIds" in step ? step.consoleIds : [], ..."consoleId" in step ? [step.consoleId] : [], ...(step.kind === "spawn" && step.near ? [step.near] : [])];
    const stray = refs.find((r) => !ids.has(r));
    if (stray) throw new Error(`planner named an unknown console ${stray}`);
    return step;
  });
}
